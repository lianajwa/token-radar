// Radar's value model: a sealed snapshot of the protocol universe in, a ranked board out.
//
// The board ranks pre-token protocols by an implied value that is derived from the snapshot's own
// figures, never from a hand-kept list of names. Three ideas make it different from a TVL table:
//
//   1. Comparables. The multiple a protocol's TVL is worth is not a fixed number: it is the
//      median market-cap-to-TVL ratio of the live-token protocols in the same snapshot, blended
//      between the whole market and the protocol's own category. A Dex and a lending market do
//      not launch at the same multiple, and the snapshot itself says so.
//   2. Growth with teeth. Seven-day TVL growth moves the value, and a fall hurts more than a
//      rise helps: a protocol bleeding TVL is not about to launch at a premium.
//   3. A maturity curve, not a ladder. A protocol that has run a couple of years with no token
//      has proven it can hold value without one, so it scores best; a brand-new one has not
//      proven anything, and one that has run five years without a token has shown it likely
//      never will. The curve peaks near two and a half years and falls on both sides.
//
// Every row also carries a farm plan derived from the protocol's own record (category, chains,
// TVL, age). The dashboard recomputes the same numbers in the page, so the code and the board
// can be checked against each other.

/** One protocol as the sealed snapshot carries it: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants. The dashboard prints them, so a reader can check the arithmetic. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_peak_days: number;
  maturity_spread_days: number;
  maturity_floor: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_steps: number;
  multiple_floor: number;
  multiple_cap: number;
  min_category_samples: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.75,
  growth_floor: -50,
  growth_cap: 150,
  maturity_peak_days: 900,
  maturity_spread_days: 800,
  maturity_floor: 0.55,
  unknown_age_days: 365,
  chain_step: 0.03,
  chain_max_steps: 4,
  multiple_floor: 0.02,
  multiple_cap: 2.5,
  min_category_samples: 3,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2-comparables';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live view carries, by market cap. */
export const LIVE_ROWS = 24;

/** Why the snapshot is not one this model can score. */
export class SnapshotError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SnapshotError';
  }
}

const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** The middle value of a sorted list, or the mean of the two middle ones. */
function median(values: number[]): number {
  const sorted = values.slice().sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  if (sorted.length === 0) return NaN;
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** Clamp `v` into [`lo`, `hi`]. */
function clamp(v: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, v));
}

/** Whole days from `from` to `to`, never below zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The comparables the snapshot itself gives: one market-cap-to-TVL multiple for the whole
 *  live market, and one per category where enough live protocols exist to trust the median. */
export interface Comparables {
  global: number;
  byCategory: Record<string, number>;
}

export function comparables(snapshot: Snapshot): Comparables {
  const live = snapshot.protocols.filter(
    (p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0 && p.category !== 'CEX',
  );
  const global = median(live.map((p) => p.mcap_usd! / p.tvl_usd));
  const groups = new Map<string, number[]>();
  for (const p of live) {
    if (p.category === null) continue;
    const list = groups.get(p.category) ?? [];
    list.push(p.mcap_usd! / p.tvl_usd);
    groups.set(p.category, list);
  }
  const byCategory: Record<string, number> = {};
  for (const [category, values] of groups) {
    if (values.length >= MODEL.min_category_samples) byCategory[category] = median(values);
  }
  return { global, byCategory };
}

/** The multiple one protocol's TVL is worth: the geometric blend of the market's multiple and
 *  its own category's, so a category's signal matters without ever deciding the number alone. */
export function multipleFor(p: SnapshotProtocol, comp: Comparables): number {
  const cat = p.category !== null ? comp.byCategory[p.category] : undefined;
  const blended = cat === undefined ? comp.global : Math.sqrt(comp.global * cat);
  return clamp(blended, MODEL.multiple_floor, MODEL.multiple_cap);
}

/** Seven-day growth as a multiplier. A fall is clamped harder than a rise: a protocol losing
 *  TVL is worth less than the same TVL standing still. */
export function growthFactor(change7d: number | null): { pct: number; mult: number } {
  const pct = clamp(finite(change7d, 0), MODEL.growth_floor, MODEL.growth_cap);
  return { pct, mult: 1 + (pct / 100) * MODEL.growth_weight };
}

/** The maturity curve: a bell that peaks at `maturity_peak_days` and falls on both sides, so a
 *  protocol scores best once it has proven it can hold value with no token, and less once it has
 *  run so long without one that a launch looks unlikely. Unknown age counts as one year. */
export function maturityCurve(age: number | null): number {
  const days = age ?? MODEL.unknown_age_days;
  const z = (days - MODEL.maturity_peak_days) / MODEL.maturity_spread_days;
  return MODEL.maturity_floor + (1 - MODEL.maturity_floor) * Math.exp(-(z * z));
}

/** Breadth: a protocol live on more chains reaches more farmers, worth a little more. */
export function breadthFactor(chains: string[]): number {
  const extra = Math.min(Math.max(chains.length - 1, 0), MODEL.chain_max_steps);
  return 1 + extra * MODEL.chain_step;
}

/** Everything one protocol's score is made of, and the implied value itself. */
export interface ScoredProtocol {
  implied: number;
  multiple: number;
  growthPct: number;
  growthMult: number;
  maturityMult: number;
  chainMult: number;
  age: number | null;
}

export function scoreProtocol(p: SnapshotProtocol, asOf: string, comp: Comparables): ScoredProtocol {
  const age = ageDays(asOf, p.listed_at);
  const multiple = multipleFor(p, comp);
  const { pct, mult: growthMult } = growthFactor(p.change_7d);
  const maturityMult = maturityCurve(age);
  const chainMult = breadthFactor(p.chains);
  const implied = Math.max(1, Math.round(p.tvl_usd * multiple * growthMult * maturityMult * chainMult));
  return { implied, multiple, growthPct: pct, growthMult, maturityMult, chainMult, age };
}

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Whether the board may rank a protocol: pre-token, not an exchange, not a versioned pool. */
export function isRankable(p: SnapshotProtocol): boolean {
  return isPreToken(p) && p.category !== 'CEX' && !VERSIONED.test(p.name);
}

/** One farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

/** One row of board.json: the ranked board's row. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  age_days: number | null;
  implied_value_usd: number;
  model: {
    comparable_multiple: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    chain_multiplier: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, comp: Comparables): BoardRow[] {
  const index = new Map(snapshot.protocols.map((p) => [p.slug, p]));
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug it names is ranked, whatever its TVL.
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: rankable pre-token protocols below the floor, by TVL, capped. A chosen
  // protocol stays chosen; the early rows only add what the floor leaves out.
  const early = snapshot.protocols
    .filter((p) => !chosen.has(p.slug) && isRankable(p) && p.tvl_usd < snapshot.floor_usd)
    .sort((a, b) => b.tvl_usd - a.tvl_usd || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
    .slice(0, EARLY_ROWS);
  for (const p of early) chosen.set(p.slug, p);

  const scored = [...chosen.values()].map((p) => ({ p, s: scoreProtocol(p, snapshot.as_of, comp) }));
  scored.sort((a, b) => b.s.implied - a.s.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map(({ p, s }, i) => ({
    rank: i + 1,
    slug: p.slug,
    name: p.name,
    category: p.category,
    chains: p.chains,
    tvl_usd: p.tvl_usd,
    change_7d: p.change_7d,
    mcap_usd: p.mcap_usd,
    listed_at: p.listed_at,
    gecko_id: p.gecko_id,
    symbol: p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      // Full precision, not rounded: the dashboard recomputes the row from this multiple,
      // and a rounded one can push the recomputed value over a display boundary.
      comparable_multiple: s.multiple,
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      chain_multiplier: round4(s.chainMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's one main action, in the words a farmer can follow. */
function mainAction(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position open.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  if (c.includes('basis')) return `Deposit $${capital} into ${name}'s basis position on ${chain} and hold it through one funding cycle.`;
  if (c.includes('privacy')) return `Use $${capital} through ${name}'s private flow on ${chain} and keep the receipt.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/** A second, category-specific signal: one repeat action that shows the farmer is a real user,
 *  not a single touch. Each is a different use of the protocol from the main action. */
function extraSignal(p: SnapshotProtocol, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('dex') || c.includes('yield')) return `Swap the same pair back once a week so the router records repeat flow, not one deposit.`;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Borrow a small amount against the supply once, then repay it, to register borrower activity.`;
  if (c.includes('bridge')) return `Bridge a small amount back on a second chain so both directions are seen.`;
  if (c.includes('staking') || c.includes('restak')) return `Delegate a second small stake after the first epoch to show ongoing use.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Close the hedge and open a fresh one once to show repeat use.`;
  if (c.includes('prediction')) return `Settle one market and enter another to show repeat participation.`;
  if (c.includes('curator') || c.includes('allocator')) return `Move a small amount between two of its vaults to show allocator activity.`;
  if (c.includes('stable')) return `Hold the stable asset through one rebalance or redemption window.`;
  if (c.includes('rwa')) return `Top the position up once after the first yield distribution lands.`;
  if (c.includes('insurance')) return `Renew or extend the cover once before it lapses.`;
  if (c.includes('basis')) return `Hold the basis position through a second funding cycle.`;
  return `Repeat the main action once after two weeks so the activity is not a single touch.`;
}

/**
 * A protocol's farm plan: seven steps, each an action with a cost and a time. The plan is
 * derived from the protocol's own record (category, chains, TVL, age), never from a hand-written
 * list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: mainAction(p, capital, chain),
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: `Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote.`,
      cost: 'about $2 of gas a week',
      time: '10 minutes a week',
    },
    {
      text: extraSignal(p, chain),
      cost: 'about $2 of gas',
      time: '10 minutes',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/** A live-token protocol: it already trades, so the board shows the market's own value, not a model's. */
export interface LiveRow {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  mcap_usd: number | null;
  change_7d: number | null;
}

/** The live-token protocols, by market cap, for the dashboard's Live view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

